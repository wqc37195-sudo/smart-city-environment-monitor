/**
  ******************************************************************************
  * @file    dht11.c
  * @brief   DHT11 温湿度传感器驱动实现
  *
  *  ============================= 工作原理 =============================
  *
  *  【通信协议：单总线】
  *  DHT11 使用自定义的单总线协议，所有通信由主机（MCU）发起：
  *
  *  步骤1：主机拉低 18ms → DHT11 检测到起始信号
  *  步骤2：主机拉高 20~40us → 释放总线
  *  步骤3：DHT11 拉低 80us → 响应信号
  *  步骤4：DHT11 拉高 80us → 准备发送数据
  *  步骤5：DHT11 发送 40bit 数据（每 bit 约 100us）
  *          "0" = 拉低 50us + 拉高 26~28us
  *          "1" = 拉低 50us + 拉高 70us
  *  步骤6：校验和验证
  *
  *  【微秒级延时】
  *  使用 Cortex-M4 的 DWT (Data Watchpoint and Trace) 周期计数器，
  *  实现精确微秒级延时，避免占用通用定时器。
  *  系统时钟 48MHz → 1 tick ≈ 20.8ns → 48 ticks/us
  *
  *  【GPIO 操作】
  *  直接操作 GPIO 寄存器（BSRR/BRR/IDR/MODER/PUPDR），
  *  不依赖 HAL_GPIO 函数，也不依赖 CubeMX 的初始化配置。
  *
  *  ==================================================================
  *
  *  接线：
  *    PB3 ──┬── DHT11 DATA
  *          └── 4.7kΩ 上拉电阻 ── 3.3V（内部上拉约40kΩ，短线可省）
  *    3.3V ──── DHT11 VCC
  *    GND  ──── DHT11 GND
  ******************************************************************************
  */
/* USER CODE END Header */

#include "dht11.h"
#include <stdio.h>

/* ---------------------------------------------------------------------------
 * 模块1：DWT 微秒延时
 * =========================================================================
 * 基于 Cortex-M4 的 DWT 周期计数器，48MHz → 1 tick ≈ 20.8ns
 * 比定时器方式更简洁，不占 TIM 资源
 * -------------------------------------------------------------------------*/

/**
  * @brief  初始化 DWT 周期计数器
  *         通过 CoreDebug 使能 TRC，然后使能 CYCCNT 计数器
  */
static void DWT_Init(void)
{
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;  /* 使能跟踪 */
    DWT->CYCCNT = 0;                                  /* 清零计数器 */
    DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;               /* 使能计数器 */
}

/**
  * @brief  微秒级延时
  * @param  us : 延时微秒数（系统 48MHz 下，1us = 48 ticks）
  * @note   忙等待，不释放 CPU
  */
static void delay_us(uint32_t us)
{
    uint32_t start = DWT->CYCCNT;
    uint32_t ticks = us * 48;  /* 48MHz = 48 ticks/us */
    while ((DWT->CYCCNT - start) < ticks);
}

/* ---------------------------------------------------------------------------
 * 模块2：GPIO 控制
 * =========================================================================
 * 直接操作 STM32 GPIO 寄存器控制 PB3
 * 寄存器	    功能                      操作
 * MODER     模式选择                  00=输入, 01=输出
 * OTYPER    输出类型                  0=推挽, 1=开漏
 * PUPDR     上下拉                    00=无, 01=上拉
 * BSRR      位设置寄存器              写1置位
 * BRR       位复位寄存器              写1复位
 * IDR       输入数据寄存器            读引脚电平
 * -------------------------------------------------------------------------*/

#define DHT11_PIN   3  /* PB3 在 GPIOB 中的位号 */

/**
  * @brief  设置 PB3 为推挽输出模式
  *         用于主机发送起始信号（拉低 18ms）
  */
static void DHT11_SetOutput(void)
{
    /* MODER[7:6] = 01 (output) */
    GPIOB->MODER &= ~(3u << (DHT11_PIN * 2));
    GPIOB->MODER |=  (1u << (DHT11_PIN * 2));
    /* OTYPER bit 3 = 0 (push-pull) */
    GPIOB->OTYPER &= ~(1u << DHT11_PIN);
    /* PUPDR — 输出时不需要上拉 */
    GPIOB->PUPDR &= ~(3u << (DHT11_PIN * 2));
}

/**
  * @brief  设置 PB3 为输入模式（带上拉）
  *         用于接收 DHT11 的响应和数据信号
  */
static void DHT11_SetInput(void)
{
    /* MODER[7:6] = 00 (input) */
    GPIOB->MODER &= ~(3u << (DHT11_PIN * 2));
    /* PUPDR[7:6] = 01 (pull-up) */
    GPIOB->PUPDR |=  (1u << (DHT11_PIN * 2));
    GPIOB->PUPDR &= ~(2u << (DHT11_PIN * 2));
}

/**
  * @brief  写 PB3 电平（输出模式时有效）
  */
static void DHT11_WritePin(uint8_t level)
{
    if (level)
        GPIOB->BSRR = (1u << DHT11_PIN);   /* Set - 置位寄存器 */
    else
        GPIOB->BRR  = (1u << DHT11_PIN);   /* Reset - 复位寄存器 */
}

/**
  * @brief  读 PB3 电平
  * @retval 0=低电平, 1=高电平
  */
static uint8_t DHT11_ReadPin(void)
{
    return (GPIOB->IDR >> DHT11_PIN) & 1;  /* IDR: 输入数据寄存器 */
}

/* ---------------------------------------------------------------------------
 * 模块3：时序等待
 * =========================================================================
 * 等待 DHT11 数据线变为指定电平，带超时保护
 * -------------------------------------------------------------------------*/

/**
  * @brief  等待 PB3 变为指定电平
  * @param  level      : 期望的电平 (0/1)
  * @param  timeout_us : 超时时间（微秒）
  * @retval 1=成功收到期望电平, 0=超时
  */
static uint8_t DHT11_WaitLevel(uint8_t level, uint32_t timeout_us)
{
    uint32_t start = DWT->CYCCNT;
    uint32_t ticks = timeout_us * 48;
    while (DHT11_ReadPin() != level)
    {
        if ((DWT->CYCCNT - start) > ticks)
            return 0;  /* 超时 */
    }
    return 1;  /* 成功 */
}

/* ---------------------------------------------------------------------------
 * 模块4：公开接口
 * =========================================================================
 * 供 main.c 调用的初始化与数据读取函数
 * -------------------------------------------------------------------------*/

/**
  * @brief  初始化 DHT11 传感器
  *         1. 使能 DWT 周期计数器（用于微秒延时）
  *         2. 置 PB3 为输出高电平（总线空闲状态）
  *         3. 等待 DHT11 上电稳定（至少 1 秒）
  * @note   在 DHT11_Read() 之前必须调用一次
  */
void DHT11_Init(void)
{
    DWT_Init();

    /* 初始置 PB3 为输出高（空闲状态） */
    DHT11_SetOutput();
    DHT11_WritePin(1);

    /* DHT11 上电后需要至少 1 秒稳定时间 */
    HAL_Delay(1500);
}

/**
  * @brief  读取 DHT11 温湿度数据
  *
  *  完整通信时序：
  *  ┌─────────────────────────────────────────────────────┐
  *  │ MCU拉低18ms  ─→  DHT11检测到起始信号                  │
  *  │ MCU拉高30us  ─→  释放总线                            │
  *  │ DHT11拉低80us ─→  响应信号                           │
  *  │ DHT11拉高80us ─→  准备发送数据                       │
  *  │ DHT11发送40bit ─→  湿度高8位+湿度低8位+温度高8位     │
  *  │                    +温度低8位+校验和                  │
  *  │ MCU校验和验证   →  成功则解析数据                     │
  *  └─────────────────────────────────────────────────────┘
  *
  * @param  data : 输出数据缓冲区（接收温湿度值）
  * @retval 0=成功, 1=通信超时, 2=校验失败
  */
uint8_t DHT11_Read(DHT11_Data *data)
{
    uint8_t buf[5] = {0};

    if (data == NULL) return 1;

    /* ==================================================================
     *  阶段1：发送起始信号
     *  MCU 拉低 ≥18ms，然后拉高 20~40us
     * ==================================================================*/
    DHT11_SetOutput();
    DHT11_WritePin(0);                   /* 拉低至少 18ms */
    HAL_Delay(20);                       /* 实际延时 20ms */
    DHT11_WritePin(1);                   /* 拉高 20~40us */
    delay_us(30);                        /* 精确延时 30us */

    /* ==================================================================
     *  阶段2：等待 DHT11 响应
     *  切换为输入模式，DHT11 会先拉低 80us 再拉高 80us
     * ==================================================================*/
    DHT11_SetInput();

    /* DHT11 拉低 80us 表示响应 */
    if (!DHT11_WaitLevel(0, 100))
    {
        data->err = 1;
        return 1;
    }
    /* DHT11 拉高 80us 准备发数据 */
    if (!DHT11_WaitLevel(1, 100))
    {
        data->err = 1;
        return 1;
    }

    /* ==================================================================
     *  阶段3：读取 40 位数据（5 字节）
     *  每位数据：DHT11 先拉低 50us，然后拉高
     *    - 拉高持续 26~28us = 逻辑 "0"
     *    - 拉高持续 70us    = 逻辑 "1"
     *  在拉高后 40us 时刻采样，若仍为高则判定为 "1"
     * ==================================================================*/
    for (int i = 0; i < 40; i++)
    {
        /* DHT11 拉低 50us（每位起始标志） */
        if (!DHT11_WaitLevel(0, 100))
        {
            data->err = 1;
            return 1;
        }
        /* DHT11 拉高：26~28us = "0", 70us = "1" */
        if (!DHT11_WaitLevel(1, 100))
        {
            data->err = 1;
            return 1;
        }
        /* 延时 40us 后采样：若仍为高则为 "1"，否则为 "0" */
        delay_us(40);
        uint8_t bit = DHT11_ReadPin();

        buf[i / 8] <<= 1;    /* 左移一位 */
        buf[i / 8] |= bit;   /* 写入当前位 */
    }

    /* ==================================================================
     *  阶段4：校验和验证
     *  校验和 = (byte0 + byte1 + byte2 + byte3) 的低 8 位
     *  如果不等，说明数据传输中发生错误
     * ==================================================================*/
    uint8_t sum = buf[0] + buf[1] + buf[2] + buf[3];
    if ((uint8_t)(sum & 0xFF) != buf[4])
    {
        data->err = 2;
        return 2;
    }

    /* ==================================================================
     *  阶段5：解析输出
     *  buf[0]=湿度整数, buf[1]=湿度小数
     *  buf[2]=温度整数, buf[3]=温度小数
     *  buf[4]=校验和
     *
     *  温度符号（DHT11 支持零下温度）：
     *    buf[2] 的 bit 7 = 1 表示负数
     * ==================================================================*/
    data->humidity_int    = buf[0];
    data->humidity_dec    = buf[1];
    data->temperature_int = buf[2];
    data->temperature_dec = buf[3];
    data->checksum        = buf[4];

    /* DHT11 温度符号位：buf[2] bit 7 = 1 表示负温度 */
    if (data->temperature_int & 0x80)
    {
        data->temperature_int = -(256 - data->temperature_int);
    }

    data->err = 0;
    return 0;
}
