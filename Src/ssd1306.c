/**
  ******************************************************************************
  * @file    ssd1306.c
  * @brief   SSD1306 OLED 128x64 驱动实现（I2C接口）
  *
  *  ============================= 架构设计 =============================
  *
  *  本驱动采用 "双缓冲" 设计：
  *  1. 帧缓冲区（Frame Buffer）：1024 字节，位于 MCU RAM 中
  *  2. GDDRAM（OLED 内部显示 RAM）：同样 1024 字节
  *
  *  所有绘图操作（写字符、画像素）先在帧缓冲区中修改，
  *  调用 SSD1306_Update() 后将整个缓冲区通过 I2C 一次性同步到 GDDRAM。
  *
  *  这样做的优点是：
  *  - 避免频繁 I2C 通信，提高效率
  *  - 防止屏幕闪烁（逐像素刷新会闪烁）
  *  - 可以批量处理多个绘图操作后再统一刷新
  *
  *  ============================= 字库 =============================
  *
  *  内嵌 5×7 标准 ASCII 字库，共 95 个字符（0x20 空格 ~ 0x7E 波浪号）。
  *  每个字符用 5 字节表示，每字节对应一列的 8 个像素位。
  *  字符间隔 1 像素，实际占宽 6 像素。
  *
  *  一行 128 像素可显示：128 / 6 ≈ 21 个字符。
  *  一屏 64 像素可分为：8 行（每行 8 像素高）。
  *
  *  ============================= 初始化 =============================
  *
  *  SSD1306 上电后默认处于关闭状态，需要发送约 25 个命令完成初始化：
  *  1. 关闭显示
  *  2. 设置时钟分频/振荡频率
  *  3. 设置多路复用比（64 行）
  *  4. 设置显示偏移
  *  5. 使能电荷泵（3.3V 供电时必须）
  *  6. 设置内存寻址模式（水平）
  *  7. 设置段重映射 / COM 扫描方向
  *  8. 设置 COM 引脚配置
  *  9. 设置对比度 / 预充电 / VCOMH
  *  10. 开启显示
  *
  *  ==================================================================
  *
  *  接线：
  *    OLED        Nucleo-WL55JC
  *    VCC    →    3.3V
  *    GND    →    GND
  *    SDA    →    PB7 (I2C1_SDA) — 与 BMP280 + GY-30 并联
  *    SCL    →    PB8 (I2C1_SCL) — 与 BMP280 + GY-30 并联
  ******************************************************************************
 */
