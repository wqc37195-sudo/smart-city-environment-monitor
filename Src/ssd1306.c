/* ---------------------------------------------------------------------------
 * 模块3：I2C 发送
 * =========================================================================
 * SSD1306 的 I2C 协议：
 *  每个数据包的第一个字节为控制字节：
 *    0x00 = 后续是命令
 *    0x40 = 后续是显示数据
 *  然后发送 1~n 字节的命令或数据
 * -------------------------------------------------------------------------*/

/**
  * @brief  发送单字节命令到 SSD1306
  * @param  cmd : 命令字节
  */
static void SSD1306_SendCmd(uint8_t cmd)
{
    uint8_t buf[2] = {SSD1306_CTRL_CMD, cmd};
    HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR_WRITE, buf, 2, HAL_MAX_DELAY);
}

/**
  * @brief  发送单字节数据到 SSD1306
  * @param  data : 数据字节
  */
static void SSD1306_SendData(uint8_t data)
{
    uint8_t buf[2] = {SSD1306_CTRL_DATA, data};
    HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR_WRITE, buf, 2, HAL_MAX_DELAY);
}

/* ---------------------------------------------------------------------------
 * 模块4：初始化序列
 * =========================================================================
 * 严格按照 SSD1306 数据手册推荐的初始化流程
 * -------------------------------------------------------------------------*/

/**
  * @brief  初始化 SSD1306 OLED 显示屏
  *
  *  发送完整的初始化命令序列:
  *    DISPLAY_OFF → CLOCK_DIV → MUX → OFFSET → START_LINE
  *    → CHARGE_PUMP → MEMORY_MODE → SEG_REMAP → COM_SCAN
  *    → COM_PINS → CONTRAST → PRECHARGE → VCOMH
  *    → DISPLAY_RAM → NORMAL_DISPLAY → DISPLAY_ON
  *
  *  最后清屏并刷新，确保屏幕初始为全黑
  */
void SSD1306_Init(void)
{
    HAL_Delay(100);  /* 等待上电稳定 */

    SSD1306_SendCmd(SSD1306_CMD_DISPLAY_OFF);
    SSD1306_SendCmd(SSD1306_CMD_SET_CLOCK_DIV);
    SSD1306_SendCmd(0x80);           /* 建议值：分频比=1, 振荡频率 */
    SSD1306_SendCmd(SSD1306_CMD_SET_MUX);
    SSD1306_SendCmd(0x3F);           /* 64行 (MUX+1) */
    SSD1306_SendCmd(SSD1306_CMD_SET_OFFSET);
    SSD1306_SendCmd(0x00);           /* 无偏移 */
    SSD1306_SendCmd(SSD1306_CMD_SET_START_LINE);
    SSD1306_SendCmd(SSD1306_CMD_CHARGE_PUMP);
    SSD1306_SendCmd(0x14);           /* 使能电荷泵 */
    SSD1306_SendCmd(SSD1306_CMD_MEMORY_MODE);
    SSD1306_SendCmd(0x00);           /* 水平寻址模式 */
    SSD1306_SendCmd(SSD1306_CMD_SEG_REMAP_R);   /* 列重映射（右侧为0） */
    SSD1306_SendCmd(SSD1306_CMD_COM_SCAN_DEC);  /* COM 扫描方向（从下到上） */
    SSD1306_SendCmd(SSD1306_CMD_SET_COM_PINS);
    SSD1306_SendCmd(0x12);           /* 建议值 */
    SSD1306_SendCmd(SSD1306_CMD_SET_CONTRAST);
    SSD1306_SendCmd(0xCF);           /* 对比度 */
    SSD1306_SendCmd(SSD1306_CMD_SET_PRECHARGE);
    SSD1306_SendCmd(0xF1);           /* 预充电周期 */
    SSD1306_SendCmd(SSD1306_CMD_SET_VCOM_DESELECT);
    SSD1306_SendCmd(0x40);           /* VCOMH 电压 */
    SSD1306_SendCmd(SSD1306_CMD_DISPLAY_RAM);    /* 显示来自 RAM */
    SSD1306_SendCmd(SSD1306_CMD_NORMAL_DISPLAY); /* 非反相 */
    SSD1306_SendCmd(SSD1306_CMD_DISPLAY_ON);

    SSD1306_Clear();
    SSD1306_Update();
}

/* ---------------------------------------------------------------------------
 * 模块5：清屏与刷新
 * =========================================================================
 *  清屏：将帧缓冲区全部置 0，光标归零
 *  刷新：将帧缓冲区通过 I2C 发送到 SSD1306 的 GDDRAM
 * -------------------------------------------------------------------------*/

/**
  * @brief  清空帧缓冲区（不刷新屏幕）
  *         调用后需要再调用 SSD1306_Update() 才能看到效果
  */
void SSD1306_Clear(void)
{
    memset(s_buffer, 0x00, sizeof(s_buffer));
    s_cursor_page = 0;
    s_cursor_col  = 0;
}

/**
  * @brief  将帧缓冲区刷新到 OLED 屏幕
  *
  *  先设置列地址范围 (0~127) 和页地址范围 (0~7)，
  *  然后分 8 批发送 1024 字节数据。
  *  每批发送 128 字节（一页的整行），加上控制字节共 129 字节。
  */
void SSD1306_Update(void)
{
    /* 设置列范围 0~127，页范围 0~7 */
    uint8_t cmd_col[] = {SSD1306_CTRL_CMD, SSD1306_CMD_SET_COLUMN_ADDR,
                         0, 127};
    uint8_t cmd_page[] = {SSD1306_CTRL_CMD, SSD1306_CMD_SET_PAGE_RANGE,
                          0, 7};

    HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR_WRITE,
                            cmd_col, 4, HAL_MAX_DELAY);
    HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR_WRITE,
                            cmd_page, 4, HAL_MAX_DELAY);

    /* 将整个缓冲区分批发送（I2C 一次最多发 128+1 = 129 字节） */
    for (uint16_t i = 0; i < sizeof(s_buffer); i += 128)
    {
        uint8_t data_buf[129];
        data_buf[0] = SSD1306_CTRL_DATA;
        memcpy(data_buf + 1, s_buffer + i, 128);
        HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR_WRITE,
                                data_buf, 129, HAL_MAX_DELAY);
    }
}

/* ---------------------------------------------------------------------------
 * 模块6：光标定位与字符输出
 * =========================================================================
 *  光标以 (page, col) 为坐标：
 *    page = 0~7（行，每行 8 像素高）
 *    col  = 0~127（列）
 *  字符宽 6 像素（5 像素字模 + 1 像素间隔）
 * -------------------------------------------------------------------------*/

/**
  * @brief  设置光标位置
  * @param  page : 页号 (0~7)
  * @param  col  : 列号 (0~127)
  */
void SSD1306_SetCursor(uint8_t page, uint8_t col)
{
    if (page >= SSD1306_PAGES) page = SSD1306_PAGES - 1;
    if (col >= SSD1306_WIDTH)  col = SSD1306_WIDTH - 1;
    s_cursor_page = page;
    s_cursor_col  = col;
}

/**
  * @brief  在当前光标位置写入一个 ASCII 字符
  * @param  ch : 要显示的字符（仅支持 0x20~0x7E）
  *
  *  自动处理换行：如果当前行剩余空间不足 6 像素，自动换到下一页。
  *  如果已经到最后一页，回卷到第 0 页。
  */
void SSD1306_WriteChar(char ch)
{
    if (ch < 0x20 || ch > 0x7E) ch = ' ';  /* 只支持 ASCII 可打印字符 */
    uint8_t idx = ch - 0x20;

    /* 检查是否换行 */
    if (s_cursor_col + 6 > SSD1306_WIDTH)
    {
        s_cursor_col = 0;
        s_cursor_page++;
        if (s_cursor_page >= SSD1306_PAGES) s_cursor_page = 0;
    }

    /* 将字模写入缓冲 */
    for (int i = 0; i < 5; i++)
    {
        uint16_t buf_pos = s_cursor_page * SSD1306_WIDTH + s_cursor_col + i;
        if (buf_pos < sizeof(s_buffer))
            s_buffer[buf_pos] = s_font[idx][i];
    }
    /* 列间空格（1 像素） */
    uint16_t blank_pos = s_cursor_page * SSD1306_WIDTH + s_cursor_col + 5;
    if (blank_pos < sizeof(s_buffer))
        s_buffer[blank_pos] = 0x00;

    s_cursor_col += 6;  /* 字符宽度 5 + 间隔 1 */
}

/**
  * @brief  在当前光标位置写入字符串
  * @param  str : 以 '\0' 结尾的 ASCII 字符串
  */
void SSD1306_WriteString(const char *str)
{
    while (str && *str)
    {
        SSD1306_WriteChar(*str);
        str++;
    }
}

/* ---------------------------------------------------------------------------
 * 模块7：像素级操作（可选）
 * =========================================================================
 *  直接操作单个像素，可用于画图、曲线等
 * -------------------------------------------------------------------------*/

/**
  * @brief  设置单个像素的颜色
  * @param  x     : 列坐标 (0~127)
  * @param  y     : 行坐标 (0~63)
  * @param  color : 0=灭, 1=亮
  */
void SSD1306_SetPixel(uint8_t x, uint8_t y, uint8_t color)
{
    if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) return;

    /* 计算像素在缓冲区中的位置
     * 每个 page 有 128 列，每列对应 1 字节中的 1 个 bit */
    uint16_t pos = (y / 8) * SSD1306_WIDTH + x;
    if (pos >= sizeof(s_buffer)) return;

    if (color)
        s_buffer[pos] |=  (1 << (y % 8));   /* 点亮该像素 */
    else
        s_buffer[pos] &= ~(1 << (y % 8));   /* 熄灭该像素 */
}

/* ---------------------------------------------------------------------------
 * 模块8：汉字显示
 * =========================================================================
 * 使用 16×16 点阵字库，按行排列（每字 32 字节）
 * 每个汉字占 16 像素宽、16 像素高（跨越 2 个 Page）
 * -------------------------------------------------------------------------*/


